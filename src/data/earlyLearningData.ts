/**
 * Validates that an EarlyLearningItem has a complete, verified label mapping and does not
 * contain filenames or missing labels (Step 7 Requirement 6A).
 */
export function validateLearningItemMapping(item: Partial<EarlyLearningItem> | null | undefined): {
  valid: boolean;
  warningUrdu?: string;
} {
  if (!item || !item.id || !item.imageVerified) {
    return {
      valid: false,
      warningUrdu: 'اس تصویر کا مستند تعلیمی نام موجود نہیں ہے۔ براہ کرم استاد سے درست نام درج کروائیں۔',
    };
  }
  const labelU = (item.objectLabelUrdu || item.word || '').trim();
  const labelE = (item.objectLabelEn || item.englishWord || '').trim();
  if (!labelU && !labelE) {
    return {
      valid: false,
      warningUrdu: 'اس کارڈ کا نام خالی ہے۔ براہ کرم استاد سے درست نام درج کروائیں۔',
    };
  }
  // Reject accidental image filenames (e.g., .png, .jpg, IMG_1234)
  if (/\.(png|jpg|jpeg|webp|svg|gif)$/i.test(labelU) || /\.(png|jpg|jpeg|webp|svg|gif)$/i.test(labelE)) {
    return {
      valid: false,
      warningUrdu: 'تصویر کے فائل نام کو بطور سبق نہیں پڑھا جا سکتا۔ براہ کرم درست نام درج کریں۔',
    };
  }
  return { valid: true };
}

/**
 * Returns the exact, mode-specific spoken text and language for any early-learning card
 * so letter names, phonics sounds, numbers, and picture labels are never confused.
 */
export function getEarlyLearningSpeechPayload(
  item: EarlyLearningItem,
  mode: EarlyLearningMode = 'full',
  activeLang: Language = 'ur'
): { text: string; lang: Language; isValid: boolean } {
  const validation = validateLearningItemMapping(item);
  if (!validation.valid) {
    return {
      text: validation.warningUrdu || 'معلومات دستیاب نہیں۔',
      lang: 'ur',
      isValid: false,
    };
  }

  // 1. Urdu Alphabet Card
  if (item.category === 'urdu') {
    const letterName = item.letterNameUrdu || item.char;
    if (mode === 'letter_name') {
      return { text: letterName, lang: 'ur', isValid: true };
    }
    if (mode === 'phonics') {
      return {
        text: item.phonicsSoundUrdu || `${letterName} سے ${item.objectLabelUrdu}`,
        lang: 'ur',
        isValid: true,
      };
    }
    if (mode === 'word_only' || mode === 'urdu_only') {
      return { text: `${letterName} سے ${item.objectLabelUrdu}`, lang: 'ur', isValid: true };
    }
    if (mode === 'english_only') {
      return { text: item.objectLabelEn, lang: 'en', isValid: true };
    }
    return {
      text: `حرف ${letterName}۔ ${letterName} سے ${item.objectLabelUrdu}۔`,
      lang: 'ur',
      isValid: true,
    };
  }

  // 2. English Alphabet Card (A–Z)
  if (item.category === 'english') {
    const letterName = item.letterNameEn || item.char;
    if (mode === 'letter_name') {
      return { text: letterName, lang: 'en', isValid: true };
    }
    if (mode === 'phonics') {
      return {
        text: item.phonicsSoundEn || `${letterName} for ${item.objectLabelEn}.`,
        lang: 'en',
        isValid: true,
      };
    }
    if (mode === 'english_only') {
      return { text: `${letterName} for ${item.objectLabelEn}.`, lang: 'en', isValid: true };
    }
    if (mode === 'urdu_only') {
      return { text: item.objectLabelUrdu, lang: 'ur', isValid: true };
    }
    if (mode === 'word_only') {
      return {
        text: activeLang === 'en' ? item.objectLabelEn : `${item.objectLabelEn}۔ ${item.objectLabelUrdu}۔`,
        lang: activeLang === 'en' ? 'en' : 'ur',
        isValid: true,
      };
    }
    // Full bilingual teaching mode: English letter & word + Urdu meaning
    return {
      text: `${letterName} for ${item.objectLabelEn}. ${item.objectLabelUrdu}۔`,
      lang: 'ur',
      isValid: true,
    };
  }

  // 3. Counting & Numbers Card
  if (item.category === 'counting') {
    const uNum = item.urduNumberWord || item.char;
    const eNum = item.englishNumberWord || item.char;
    if (mode === 'urdu_only' || (mode === 'letter_name' && activeLang !== 'en')) {
      return { text: uNum, lang: 'ur', isValid: true };
    }
    if (mode === 'english_only' || (mode === 'letter_name' && activeLang === 'en')) {
      return { text: eNum, lang: 'en', isValid: true };
    }
    if (mode === 'word_only') {
      return {
        text: activeLang === 'en' ? item.objectLabelEn : item.objectLabelUrdu,
        lang: activeLang === 'en' ? 'en' : 'ur',
        isValid: true,
      };
    }
    if (activeLang === 'en') {
      return { text: `${eNum}. ${item.objectLabelEn}.`, lang: 'en', isValid: true };
    }
    return {
      text: `${uNum}۔ ${eNum}. ${item.objectLabelUrdu}۔`,
      lang: 'ur',
      isValid: true,
    };
  }

  // 4. Objects, Colors, Shapes & Animals
  if (mode === 'english_only' || activeLang === 'en') {
    return { text: item.objectLabelEn, lang: 'en', isValid: true };
  }
  if (mode === 'urdu_only') {
    return { text: item.objectLabelUrdu, lang: 'ur', isValid: true };
  }
  return {
    text: `${item.objectLabelUrdu}۔ ${item.objectLabelEn}.`,
    lang: 'ur',
    isValid: true,
  };
}
