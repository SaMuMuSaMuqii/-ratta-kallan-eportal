// Math expression evaluator for children questions like "3500 * 4" or "12 + 18"
const trySolveArithmetic = (query: string): string | null => {
  // Replace words with symbols
  const clean = query
    .replace(/ضرب/g, '*')
    .replace(/تقسیم/g, '/')
    .replace(/جمع/g, '+')
    .replace(/منفی|تفریق/g, '-')
    .replace(/times|multiplied by/gi, '*')
    .replace(/plus/gi, '+')
    .replace(/minus/gi, '-')
    .replace(/divided by/gi, '/');

  const match = clean.match(/(\d+(?:\.\d+)?)\s*([\+\-\*\/])\s*(\d+(?:\.\d+)?)/);
  if (match) {
    const a = parseFloat(match[1]);
    const op = match[2];
    const b = parseFloat(match[3]);
    let result = 0;
    if (op === '+') result = a + b;
    else if (op === '-') result = a - b;
    else if (op === '*') result = a * b;
    else if (op === '/' && b !== 0) result = Math.round((a / b) * 100) / 100;

    return `حساب کا حل:\n${a} ${op === '*' ? '×' : op === '/' ? '÷' : op} ${b} = ${result}\nشاباش بیٹا! آپ کا جواب بالکل درست اور واضح ہے۔`;
  }
  return null;
};

